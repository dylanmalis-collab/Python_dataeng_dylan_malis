import math
import numpy as np
PI = math.pi
E = math.e
def carre(x):
    return x**2
def cube(x):
    return x**3
def factorielle(n):
    return math.factorial(n)
def valeur_absolue(x):
    return math.fabs(x)
def maximum(liste):
    return max(liste)
def minimum(liste):
    return min(liste)
def moyenne(liste):
    np.mean(liste)
def ecart_type(liste):
    np.std(liste)
def mediane(liste):
    np.median(liste)
